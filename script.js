let currentLanguage = "en";
let currentTemplate = "professional";
let aiObjectiveText = "";
let objectiveRequestId = 0;
let objectiveRequestController = null;
const selectedSkills = new Set();
const form = document.getElementById("resumeForm");
const $ = (id) => document.getElementById(id);

function invalidateAiObjective() {
  aiObjectiveText = "";
  if (!objectiveRequestController) return;
  objectiveRequestId += 1;
  objectiveRequestController.abort();
  objectiveRequestController = null;
  $("generateObjective").removeAttribute("aria-busy");
  $("generateObjective").disabled = !$("aiConsent").checked;
  $("objectiveStatus").textContent = "";
}

function setLanguage(language) {
  if (language !== currentLanguage) invalidateAiObjective();
  currentLanguage = language;
  const dictionary = langData[language];
  document.documentElement.lang = language;
  document.body.classList.toggle("lang-hi", language === "hi");
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const translation = dictionary[element.dataset.i18n];
    if (typeof translation === "string") element.textContent = translation;
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const translation = dictionary[element.dataset.i18nPlaceholder];
    if (typeof translation === "string") element.placeholder = translation;
  });
  document.querySelectorAll(".language-option").forEach((button) => {
    const active = button.dataset.language === language;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", String(active));
  });
  renderExperienceYearOptions();
  renderJobRoleOptions();
  renderSkills();
  updatePreview();
}

function renderJobRoleOptions() {
  const select = $("jobRole");
  const selectedRole = select.value || "computerOperator";
  const dictionary = langData[currentLanguage];
  select.replaceChildren(new Option(dictionary.selectOption, ""));
  jobCategories.forEach((category) => {
    const group = document.createElement("optgroup");
    group.label = category[currentLanguage];
    jobRoles.filter((role) => role.category === category.value).forEach((role) => {
      group.append(new Option(role[currentLanguage], role.value));
    });
    select.append(group);
  });
  select.value = selectedRole;
  if (!select.value) select.value = "computerOperator";
}

function renderExperienceYearOptions() {
  const select = $("experienceYears");
  const selectedValue = select.value || "fresher";
  const dictionary = langData[currentLanguage];
  const locale = currentLanguage === "hi" ? "hi-IN" : "en-IN";
  const options = [new Option(dictionary.fresher, "fresher"), new Option(dictionary.lessThanOneYear, "lessThanOne")];

  for (let year = 1; year <= 30; year += 1) {
    const formattedYear = new Intl.NumberFormat(locale).format(year);
    const unit = year === 1 ? dictionary.yearSingular : dictionary.yearPlural;
    options.push(new Option(`${formattedYear} ${unit}`, String(year)));
  }
  const moreThanThirty = new Intl.NumberFormat(locale).format(30);
  options.push(new Option(`${moreThanThirty}+ ${dictionary.yearPlural}`, "30plus"));
  select.replaceChildren(...options);
  select.value = selectedValue;
  if (!select.value) select.value = "fresher";
}

function renderSkills() {
  const list = $("skillsList");
  list.replaceChildren();
  skillData.forEach((skill, index) => {
    const button = document.createElement("button");
    button.type = "button";
    button.className = `skill-chip${selectedSkills.has(index) ? " selected" : ""}`;
    button.textContent = skill[currentLanguage];
    button.setAttribute("aria-pressed", String(selectedSkills.has(index)));
    button.addEventListener("click", () => {
      if (selectedSkills.has(index)) selectedSkills.delete(index);
      else selectedSkills.add(index);
      renderSkills();
      updatePreview();
    });
    list.append(button);
  });
}

function value(id) {
  return $(id).value.trim();
}

function setText(id, text, fallback = "—") {
  $(id).textContent = text || fallback;
}

function formatDate(rawDate) {
  if (!rawDate) return "";
  const date = new Date(`${rawDate}T00:00:00`);
  return new Intl.DateTimeFormat(currentLanguage === "hi" ? "hi-IN" : "en-IN", {
    day: "numeric", month: "long", year: "numeric"
  }).format(date);
}

function appendDetail(list, label, detail) {
  if (!detail) return;
  const item = document.createElement("div");
  const term = document.createElement("dt");
  const description = document.createElement("dd");
  term.textContent = `${label}:`;
  description.textContent = detail;
  item.append(term, description);
  list.append(item);
}

function generateCareerObjective() {
  const role = jobRoles.find((item) => item.value === $("jobRole").value) || jobRoles[jobRoles.length - 1];
  const language = currentLanguage;
  const selectedYears = $("experienceYears").value;
  const qualification = $("qualification").value === "other"
    ? value("otherCourse")
    : $("qualification").value
      ? $("qualification").selectedOptions[0].textContent
      : "";
  const educationContext = [
    qualification,
    value("board"),
    value("passingYear")
  ].filter(Boolean).join(language === "hi" ? " - " : ", ");
  const skills = Array.from(selectedSkills, (index) => skillData[index][language]).slice(0, 4);
  const skillsText = skills.length
    ? skills.join(language === "hi" ? ", " : ", ")
    : role[language === "hi" ? "hiStrength" : "enStrength"];
  const experienceDetails = selectedYears === "fresher" ? "" : value("experienceDetails");

  if (language === "hi") {
    const education = educationContext
      ? `मेरी शैक्षणिक पृष्ठभूमि ${educationContext} है।`
      : "";
    const yearsDescription = selectedYears === "lessThanOne"
      ? "1 वर्ष से कम"
      : selectedYears === "30plus"
        ? "30 वर्ष से अधिक"
        : `${new Intl.NumberFormat("hi-IN").format(Number(selectedYears))} वर्ष`;
    const experience = selectedYears === "fresher"
      ? "मैं नई जिम्मेदारियाँ सीखने और पूरी लगन से काम करने के लिए तैयार हूँ।"
      : `${yearsDescription} का अनुभव${experienceDetails ? ` (${experienceDetails})` : ""} मुझे इस भूमिका में योगदान देने में मदद करेगा।`;
    return [
      `मैं ${role.hi} के पद पर कार्य करते हुए ${role.hiWork} में योगदान देना चाहता/चाहती हूँ।`,
      education,
      `मेरी प्रमुख योग्यताएँ ${skillsText} हैं।`,
      experience
    ].filter(Boolean).join(" ");
  }

  const education = educationContext ? `My academic background includes ${educationContext}.` : "";
  const yearsDescription = selectedYears === "lessThanOne"
    ? "Less than one year"
    : selectedYears === "30plus"
      ? "More than 30 years"
      : `${selectedYears} ${Number(selectedYears) === 1 ? "year" : "years"}`;
  const experience = selectedYears === "fresher"
    ? "I am ready to learn new responsibilities and contribute with dedication."
    : `${yearsDescription} of experience${experienceDetails ? ` in ${experienceDetails}` : ""} has prepared me to contribute effectively.`;
  return [
    `I am seeking a ${role.en} role where I can contribute to ${role.enWork}.`,
    education,
    `My strengths include ${skillsText}.`,
    experience
  ].filter(Boolean).join(" ");
}

function updatePreview() {
  const dictionary = langData[currentLanguage];
  const fullName = value("fullName");
  setText("previewName", fullName, dictionary.yourName);
  setText("previewSignature", fullName, dictionary.yourName);

  const contact = [value("phone"), value("email")].filter(Boolean).join("  |  ");
  setText("previewContact", contact, "");

  $("previewObjective").textContent = aiObjectiveText || generateCareerObjective();

  const personal = $("previewPersonal");
  personal.replaceChildren();
  appendDetail(personal, dictionary.fatherLabel, value("fatherName"));
  appendDetail(personal, dictionary.dobLabel, formatDate(value("dob")));
  const gender = $("gender").value;
  appendDetail(personal, dictionary.genderLabel, gender ? dictionary[gender] : "");
  const maritalStatus = $("maritalStatus").value;
  appendDetail(personal, dictionary.maritalLabel, maritalStatus ? dictionary[maritalStatus] : "");
  appendDetail(personal, dictionary.addressLabel, value("address"));

  const course = $("qualification").value === "other"
    ? value("otherCourse")
    : $("qualification").value
      ? $("qualification").selectedOptions[0].textContent
      : "";
  setText("previewQualification", course);
  setText("previewBoard", value("board"));
  setText("previewYear", value("passingYear"));
  setText("previewPercentage", value("percentage"));

  const selectedYears = $("experienceYears").value;
  const yearsLabel = selectedYears === "lessThanOne"
    ? dictionary.lessThanOneYear
    : selectedYears === "30plus"
      ? `${new Intl.NumberFormat(currentLanguage === "hi" ? "hi-IN" : "en-IN").format(30)}+ ${dictionary.yearPlural}`
      : selectedYears === "fresher"
        ? ""
        : `${new Intl.NumberFormat(currentLanguage === "hi" ? "hi-IN" : "en-IN").format(Number(selectedYears))} ${Number(selectedYears) === 1 ? dictionary.yearSingular : dictionary.yearPlural}`;
  const experience = selectedYears === "fresher"
    ? dictionary.fresher
    : [yearsLabel, value("experienceDetails")].filter(Boolean).join(" — ");
  setText("previewExperience", experience, dictionary.fresher);
  $("previewSkills").replaceChildren(...Array.from(selectedSkills, (index) => {
    const item = document.createElement("li");
    item.textContent = skillData[index][currentLanguage];
    return item;
  }));
  $("previewDeclaration").textContent = dictionary.declarationText;
  setText("previewPlace", value("place"));
  setText("previewDate", formatDate(value("declarationDate")));
}

