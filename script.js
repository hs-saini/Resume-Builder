$("generateObjective").addEventListener("click", async () => {
  const dictionary = langData[currentLanguage];
  if (!$("aiConsent").checked) return;

  const role = jobRoles.find((item) => item.value === $("jobRole").value) || jobRoles[jobRoles.length - 1];
  const qualification = $("qualification").value === "other"
    ? value("otherCourse")
    : $("qualification").value
      ? $("qualification").selectedOptions[0].textContent
      : "";
  const years = $("experienceYears").value;
  const button = $("generateObjective");
  const requestId = ++objectiveRequestId;
  const controller = new AbortController();
  objectiveRequestController = controller;
  button.disabled = true;
  button.setAttribute("aria-busy", "true");
  $("objectiveStatus").textContent = dictionary.generatingObjective;

  try {
    const response = await fetch("/api/objective", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      signal: controller.signal,
      body: JSON.stringify({
        language: currentLanguage,
        role: role[currentLanguage],
        education: [qualification, value("board"), value("passingYear")].filter(Boolean).join(", "),
        skills: Array.from(selectedSkills, (index) => skillData[index][currentLanguage]),
        yearsExperience: years === "fresher" ? "Fresher" : years,
        experienceDetails: value("experienceDetails")
      })
    });
    let result;
    try {
      result = await response.json();
    } catch {
      throw new Error("AI objective service returned an invalid response.");
    }
    if (requestId !== objectiveRequestId) return;
    if (!response.ok || typeof result.objective !== "string" || !result.objective.trim()) {
      throw new Error(result.error || "Objective generation request failed.");
    }
    aiObjectiveText = result.objective.trim();
    updatePreview();
    $("objectiveStatus").textContent = dictionary.objectiveGenerated;
  } catch (error) {
    if (requestId !== objectiveRequestId) return;
    aiObjectiveText = "";
    updatePreview();
    $("objectiveStatus").textContent = dictionary.objectiveGenerationFailed;
    if (error.name !== "AbortError") console.error("Career objective generation failed:", error.message);
  } finally {
    if (requestId === objectiveRequestId) {
      objectiveRequestController = null;
      button.removeAttribute("aria-busy");
      button.disabled = !$("aiConsent").checked;
    }
  }
});
